public class Activity1_Sarmiento {

    public static void main(String[] args) {

        // boolean - true or false
        boolean isJavaFun = true;

        // byte - small integer (-128 to 127)
        byte byteValue = 100;

        // short - small/medium integer
        short shortValue = 32000;

        // int - regular integer
        int intValue = 123456;

        // long - large integer (L suffix required)
        long longValue = 12345678910L;

        // float - decimal number (F suffix required)
        float floatValue = 12.34F;

        // double - larger decimal number
        double doubleValue = 12345.6789;

        // char - single character
        char charValue = 'J';

        // String - text
        String stringValue = "Hello Java World";

        // Output all values
        System.out.println("Boolean value: " + isJavaFun);
        System.out.println("Byte value: " + byteValue);
        System.out.println("Short value: " + shortValue);
        System.out.println("Int value: " + intValue);
        System.out.println("Long value: " + longValue);
        System.out.println("Float value: " + floatValue);
        System.out.println("Double value: " + doubleValue);
        System.out.println("Char value: " + charValue);
        System.out.println("String value: " + stringValue);
    }
}